      url "https://github.com/Murzav/xcstrings-mcp/releases/download/v#{version}/xcstrings-mcp-aarch64-apple-darwin.tar.gz"
      sha256 "da6a28e174299b6f9f5adf379ad113da8fe41858c77f0444b075fb970292989e"

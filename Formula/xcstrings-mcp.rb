      url "https://github.com/Murzav/xcstrings-mcp/releases/download/v#{version}/xcstrings-mcp-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "725c5d3defba659fcac3c13af755f79c99fb584b51346df1789d85dfe07f3a29"
